/**
 * Коэффициент похожести строк 0..1 — фолбэк, когда в БД нет pg_trgm
 * (§4.2, примечание: KNOWLEDGE_SEARCH_MODE=fts_only).
 *
 * Считаем по триграммам, а не по расстоянию Левенштейна: для коротких
 * вопросов Левенштейн даёт почти нули на перестановках слов, а триграммы
 * ловят частичные совпадения.
 */
export function trigramSimilarity(a: string, b: string): number {
  const left = pad(a);
  const right = pad(b);
  if (!left.length || !right.length) return 0;

  const grams = (s: string): Map<string, number> => {
    const m = new Map<string, number>();
    for (let i = 0; i + 3 <= s.length; i += 1) {
      const g = s.slice(i, i + 3);
      m.set(g, (m.get(g) ?? 0) + 1);
    }
    return m;
  };

  const ga = grams(left);
  const gb = grams(right);
  let shared = 0;
  let total = 0;
  for (const [g, n] of ga) {
    total += n;
    shared += Math.min(n, gb.get(g) ?? 0);
  }
  for (const [, n] of gb) total += n;

  if (total === 0) return 0;
  return (2 * shared) / total;
}

/** Обёртка строки маркерами — триграммы на краях ловят приставки/окончания. */
function pad(s: string): string {
  const t = (s ?? '').trim();
  return t ? `  ${t}  ` : '';
}