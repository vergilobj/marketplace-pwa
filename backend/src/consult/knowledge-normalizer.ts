/**
 * Нормализовать текст вопроса.
 *
 * Порядок важен: ё→е делаем ДО разбиения на слова, иначе стоп-слово «ещё»
 * не совпадёт с «еще».
 */
export function normalize(text: string): string {
  const lower = (text ?? '').toLowerCase().replace(/ё/g, 'е');
  const cleaned = lower
    .replace(/[^a-zа-я0-9\s]+/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  if (!cleaned) return '';
  return cleaned
    .split(' ')
    .filter((w) => w.length > 1 && !STOP_WORDS.has(w))
    .join(' ');
}

/**
 * Значимые слова вопроса (без стоп-слов и односимвольного мусора).
 * Используется для keyword-поиска, когда триграммы недоступны.
 */
export function extractKeywords(text: string): string[] {
  const norm = normalize(text);
  if (!norm) return [];
  const seen = new Set<string>();
  const out: string[] = [];
  for (const w of norm.split(' ')) {
    if (w.length < 3 || seen.has(w)) continue;
    seen.add(w);
    out.push(w);
  }
  return out;
}

/**
 * Слова, по которым вообще есть смысл искать ответ в базе знаний.
 * Отличается от `extractKeywords` тем, что пропускает общие слова
 * («сколько», «стоит», «цена»), которые есть почти в каждом вопросе и
 * дают ложные совпадения.
 */
export function extractTopics(text: string): string[] {
  return extractKeywords(text).filter((w) => !GENERIC_WORDS.has(w));
}

